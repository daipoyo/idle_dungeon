def paint(rows, pal):
    """数字の文字マップ → 色記号の2次元リスト。pal は色記号の文字列。"""
    out = []
    for r in rows:
        out.append([None if ch == '.' else pal[int(ch)] for ch in r])
    return out


def check(rows, w, h, name):
    assert len(rows) == h, (name, len(rows))
    for r in rows:
        assert len(r) == w, (name, r)


