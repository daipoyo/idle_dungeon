def mirror(half):
    return [r + r[::-1] for r in half]


def keeper_bust():
    rows = mirror(KEEPER_BUST_HALF)
    return [[None if ch == '.' else ch for ch in r] for r in rows]


def keeper_face():
    """一覧画面の見出しに出す顔 (22x22)。上半身の絵の上側を切り出す。"""
    bust = keeper_bust()
    return [row[3:25] for row in bust[0:22]]
