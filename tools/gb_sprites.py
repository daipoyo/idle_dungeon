def hero_hand(rows):
    """胴体部分で一番右下にある手(e)の座標。武器の取り付け位置に使う。"""
    best = None
    for y in range(len(HERO_HEAD), len(HERO_HEAD) + 5):
        for x, ch in enumerate(rows[y]):
            if ch == 'e' and (best is None or (x, y) > best):
                best = (x, y)
    return best


def weapon_anchor(rows):
    """武器マップ内の握り手(最初の e)の座標。"""
    for y, r in enumerate(rows):
        x = r.find('e')
        if x >= 0:
            return (x, y)
    raise ValueError('weapon map has no hand')


