def add_outline_to_map(rows):
    h = len(rows)
    w = max(len(r) for r in rows)
    grid = [list(r.ljust(w, '.')) for r in rows]
    out = [row[:] for row in grid]
    for y in range(h):
        for x in range(w):
            if grid[y][x] != '.':
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                xx, yy = x + dx, y + dy
                if 0 <= xx < w and 0 <= yy < h and grid[yy][xx] != '.':
                    out[y][x] = 'K'
                    break
    return [''.join(r) for r in out]


def pad_map(rows, n=1):
    w = max(len(x) for x in rows)
    rows = [x.ljust(w, '.') for x in rows]
    blank = '.' * (w + n * 2)
    return [blank] * n + ['.' * n + x + '.' * n for x in rows] + [blank] * n


def weapon_maps():
    def mk(rows):
        # 手の部分は輪郭を付けない（勇者の手に重なるため）
        out = add_outline_to_map(pad_map([r.replace('e', '.') for r in rows]))
        ax, ay = weapon_anchor(rows)
        row = list(out[ay + 1])
        row[ax + 1] = 'e'
        out[ay + 1] = ''.join(row)
        return out
    return {
        'SWORD_REST': mk(SWORD_REST),
        'SWORD_SWING': mk(SWORD_SWING),
        'AXE_REST': mk(AXE_REST),
        'AXE_SWING': mk(AXE_SWING),
    }


