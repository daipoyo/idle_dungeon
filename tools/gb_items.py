# ------------------------------------------------------------
# items.h / items.c から並び順を読む（C とずれないように）
# ------------------------------------------------------------
def read_catalog(root):
    items_h = open(os.path.join(root, 'src', 'c', 'items.h'), encoding='utf-8').read()
    shapes = re.findall(r'X\((\w+), "([^"]+)", (SLOT_\w+), (FAM_\w+),', items_h)
    items_c = open(os.path.join(root, 'src', 'c', 'items.c'), encoding='utf-8').read()
    specials = re.findall(r'\{ "((?:[^"\\]|\\.)+)", SH_(\w+), (\d+),', items_c)
    return shapes, specials


FAMILY_INDEX = {'FAM_METAL': 0, 'FAM_SOFT': 1, 'FAM_WOOD': 2, 'FAM_JEWEL': 3}


def shape_rows(shape_id):
    accents, rows = SHAPES[shape_id]
    rows = shade(rows)
    check(shape_id, rows)
    return accents, rows


def special_rows(name, shape_id):
    if name in UNIQUE_ART:
        rows = shade(UNIQUE_ART[name])
        check(name, rows)
        return rows
    return shape_rows(shape_id)[1]


# ------------------------------------------------------------
# 書き出し
# ------------------------------------------------------------
def argb8(pal, c):
    r, g, b = pal[c]
    return 0xC0 | ((r // 85) << 4) | ((g // 85) << 2) | (b // 85)


def record(pal, colors6, rows):
    """6色（輪郭・暗・中・明・固定2）+ 12x12 を 4bit で詰めた 78バイト。"""
    out = bytearray(argb8(pal, c) for c in colors6)
    nibbles = []
    for r in rows:
        for ch in r:
            nibbles.append(0 if ch == '.' else int(ch) + 1)
    for i in range(0, len(nibbles), 2):
        out.append((nibbles[i] << 4) | nibbles[i + 1])
    assert len(out) == 78
    return bytes(out)


def build(root, pal):
    shapes, specials = read_catalog(root)
    missing = [sid for sid, _, _, _ in shapes if sid not in SHAPES]
    assert not missing, 'shapes without art: %s' % missing
    assert len(shapes) == 150 and len(specials) == 100, (len(shapes), len(specials))
    unknown = [name for name, _, set_id in specials if set_id == '0' and name not in UNIQUE_COLORS]
    assert not unknown, 'uniques without colors: %s' % unknown

    data = bytearray()
    for sid, _, _, fam in shapes:
        accents, rows = shape_rows(sid)
        tier0 = FAMILIES[FAMILY_INDEX[fam]][1][0][1]
        data += record(pal, 'K' + tier0 + accents, rows)
    for name, sid, set_id in specials:
        set_id = int(set_id)
        colors = SET_COLORS[set_id - 1] if set_id else UNIQUE_COLORS[name]
        data += record(pal, 'K' + colors, special_rows(name, sid))

    data_dir = os.path.join(root, 'resources', 'data')
    os.makedirs(data_dir, exist_ok=True)
    with open(os.path.join(data_dir, 'item_icons.bin'), 'wb') as f:
        f.write(bytes(data))

    lines = [
        '// このファイルは tools/gen_art.py（tools/gb_items.py）で自動生成されています。直接編集しないでください。',
        '#pragma once',
        '#include <pebble.h>',
        '',
        '// 図鑑アイテムの絵: 12x12 ドット、1つ 78バイト（6色 + 4bit の絵）',
        '#define ITEM_ICON_DOTS %d' % N,
        '#define ITEM_ICON_RECORD 78',
        '#define ITEM_ICON_SPECIAL_FIRST %d   // 固有・セット装備の絵はこの番号から' % len(shapes),
        '',
        '// 素材の色（暗・中・明）[系統][段階]',
        'static const uint8_t ITEM_TIER_COLORS[4][6][3] = {',
    ]
    for fname, tiers in FAMILIES:
        cells = ', '.join('{ %s }' % ', '.join('0x%02X' % argb8(pal, c) for c in colors)
                          for _, colors in tiers)
        lines.append('  { %s },  // %s' % (cells, fname))
    lines.append('};')
    with open(os.path.join(root, 'src', 'c', 'item_art.h'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    return shapes, specials


def preview(root, pal, out_dir, new_image, upscale):
    """確認用: 形 x 素材6段階の一覧と、固有・セット装備の一覧。"""
    import gb_font
    shapes, specials = read_catalog(root)

    def draw_text(img, x, y, text, color):
        for ch in text.upper():
            w, bits = gb_font.encode(ch)
            for gy, v in enumerate(bits):
                for gx in range(w):
                    if v >> gx & 1:
                        img.putpixel((x + gx, y + gy), color + (255,))
            x += w + 1

    def icon(rows, colors6):
        img = new_image(N, N)
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch != '.':
                    img.putpixel((x, y), pal[colors6[int(ch)]] + (255,))
        return upscale(img, 2)

    def black(w, h):
        img = new_image(w, h)
        img.paste((0, 0, 0, 255), (0, 0, w, h))
        return img

    cols = 5
    cell_w, cell_h = 250, 32
    per_page = 50
    for page in range(0, len(shapes), per_page):
        chunk = shapes[page:page + per_page]
        rows_n = math.ceil(len(chunk) / cols)
        img = black(cols * cell_w, rows_n * cell_h + 8)
        for i, (sid, name, _, fam) in enumerate(chunk):
            accents, rows = shape_rows(sid)
            x = (i % cols) * cell_w + 4
            y = (i // cols) * cell_h + 4
            for t, (_, colors) in enumerate(FAMILIES[FAMILY_INDEX[fam]][1]):
                img.alpha_composite(icon(rows, 'K' + colors + accents), (x + t * 26, y))
            draw_text(img, x + 6 * 26 + 2, y + 8, name[:10], (0xAA, 0xAA, 0xAA))
        upscale(img, 2).save(os.path.join(out_dir, 'pv_item_shapes_%d.png' % (page // per_page + 1)))

    cols = 4
    cell_w = 180
    rows_n = math.ceil(len(specials) / cols)
    img = black(cols * cell_w, rows_n * cell_h + 8)
    for i, (name, sid, set_id) in enumerate(specials):
        set_id = int(set_id)
        colors = SET_COLORS[set_id - 1] if set_id else UNIQUE_COLORS[name]
        x = (i % cols) * cell_w + 4
        y = (i // cols) * cell_h + 4
        img.alpha_composite(icon(special_rows(name, sid), 'K' + colors), (x, y))
        color = (0x55, 0xFF, 0x55) if set_id else (0xFF, 0xAA, 0x00)
        draw_text(img, x + 28, y + 8, name[:18], color)
    upscale(img, 2).save(os.path.join(out_dir, 'pv_item_specials.png'))
