"""図鑑アイテムの絵（12x12 ドット・6色）。

絵の記号:
  '#'         = 素材（左上を明るく、右下を暗く、自動で陰影をつける）
  '1' '2' '3' = 素材の暗・中・明（陰影を手で決めたいとき）
  '4' '5'     = 形ごとに決まった色（柄の革、鍔の金、宝石など。素材では変わらない）
  '0'         = 輪郭・くぼみ（黒）
  '.'         = 透明

基本アイテム（形 150種）は素材の段階ごとに 1〜3 の色を差し替えて描く。
固有・セット装備は専用の6色（セットは3部位で同じ色）を持ち、ボスの固有装備などは専用の絵を持つ。

書き出し（gen_art.py から呼ぶ）:
  resources/data/item_icons.bin … 1アイコン 78バイト（6色 + 12x12 を 4bit で 72バイト）
  src/c/item_art.h              … アイコンの大きさと、素材の色の表
"""
