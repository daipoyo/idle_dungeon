# ------------------------------------------------------------
# 描くための道具
# ------------------------------------------------------------
def blank():
    return [['.'] * N for _ in range(N)]


def rows_of(grid):
    return [''.join(r) for r in grid]


def put(g, x, y, c):
    if 0 <= x < N and 0 <= y < N:
        g[y][x] = c


def check(name, rows):
    assert len(rows) == N, (name, len(rows))
    for r in rows:
        assert len(r) == N, (name, r, len(r))
        assert all(ch in '.#012345' for ch in r), (name, r)


def shade(rows):
    """'#' を、左上が明るく右下が暗くなるように 3/2/1 に塗り分ける。"""
    g = [list(r) for r in rows]

    def empty(x, y):
        return not (0 <= x < N and 0 <= y < N) or g[y][x] in '.0'

    out = [r[:] for r in g]
    for y in range(N):
        for x in range(N):
            if g[y][x] != '#':
                continue
            if empty(x, y - 1) or empty(x - 1, y):
                out[y][x] = '3'
            elif empty(x, y + 1) or empty(x + 1, y):
                out[y][x] = '1'
            else:
                out[y][x] = '2'
    return rows_of(out)


def over(base, patch):
    """patch の '_' 以外の文字で base を上書きする。"""
    out = []
    for b, p in zip(base, patch):
        out.append(''.join(pc if pc != '_' else bc for bc, pc in zip(b, p)))
    return out


def texture(rows, a='1', b='3'):
    """中間色 '2' のところを市松模様にする（鎖かたびらなど）。"""
    out = []
    for y, r in enumerate(rows):
        out.append(''.join((a if (x + y) % 2 else b) if ch == '2' else ch for x, ch in enumerate(r)))
    return out


def blank_rows():
    return ['.' * N] * N


# ------------------------------------------------------------
# 剣・短剣（右上を向いた斜めの剣を寸法から作る）
#   p = 左下(0,11) から右上(11,0) への斜めの位置
# ------------------------------------------------------------
def sword(blade, widths, guard='cross', guard_len=1, grip=2, pommel=1, curve=0.0, wave=False,
          start=0, wrap=False):
    g = blank()
    p = start

    def cell(pp):
        return pp, N - 1 - pp

    for _ in range(pommel):
        x, y = cell(p)
        put(g, x, y, '5')
        p += 1
    for i in range(grip):
        x, y = cell(p)
        put(g, x, y, '5' if (wrap and i % 2) else '4')
        p += 1
    gx, gy = cell(p)
    for i in range(blade):
        t = (i + 1) / blade
        w = widths[min(i, len(widths) - 1)]
        off = int(round(curve * t * t))
        if wave:
            off += i % 2
        x, y = cell(p + 1 + i)
        for k, c in enumerate({1: '3', 2: '32', 3: '321', 4: '3221'}[w]):
            put(g, x + off + k, y, c)
    if guard == 'cross':
        for i in range(-guard_len, guard_len + 1):
            put(g, gx + i, gy + i, '5')
    elif guard == 'disc':
        for dx, dy in [(0, 0), (1, 0), (-1, 0), (0, 1), (0, -1)]:
            put(g, gx + dx, gy + dy, '5')
    elif guard == 'bow':
        for i in (-1, 0, 1):
            put(g, gx + i, gy + i, '5')
        for j in range(grip + 1):
            put(g, gx + 1 - j, gy + 1 + j, '5')
    return rows_of(g)


