def encode(ch):
    g = GLYPHS.get(ch)
    if g is None:
        g = GLYPHS[ch.upper()] if ch.upper() in GLYPHS else GLYPHS['?']
    w = len(g[0])
    bits = []
    for row in g:
        assert len(row) == w, (ch, g)
        v = 0
        for x, c in enumerate(row):
            if c == '#':
                v |= 1 << x
        bits.append(v)
    return w, bits


def preview():
    text = [
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ",
        "0123456789 !\"#$%&'()*+,-./",
        ":;<=>?@[\\]^_`{|}~",
        "WELCOME, DARLING~ +120G",
    ]
    img = Image.new('RGB', (4 * 30 + 4, 7 * len(text) + 4), (0, 0, 0))
    for li, line in enumerate(text):
        x = 2
        for ch in line:
            w, bits = encode(ch)
            for y, v in enumerate(bits):
                for xx in range(w):
                    if v >> xx & 1:
                        img.putpixel((x + xx, 2 + li * 7 + y), (255, 255, 255))
            x += w + 1
    return img
